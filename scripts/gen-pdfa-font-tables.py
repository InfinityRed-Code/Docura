"""Generate crates/pdf_pdfa/src/fonts/tables.rs from pdf.js sources.

The tables (standard encodings with glyph names, the Adobe Glyph List,
the ZapfDingbats glyph list and the standard-14 font widths) come from
pdf.js (Apache License 2.0, https://github.com/mozilla/pdf.js):
src/core/encodings.js, src/core/glyphlist.js, src/core/metrics.js.

    python -I scripts/gen-pdfa-font-tables.py <dir with the pdf.js files>
"""

import os
import re
import sys

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = os.path.join(root, "crates", "pdf_pdfa", "src", "fonts", "tables.rs")


def read(name):
    with open(os.path.join(src, name), encoding="utf-8") as f:
        return f.read()


enc_js = read("encodings.js")


def encoding(name):
    m = re.search(r"const %s = \[(.*?)\];" % name, enc_js, re.S)
    names = re.findall(r'"([^"]*)"', m.group(1))
    assert len(names) == 256, (name, len(names))
    return names


glyph_js = read("glyphlist.js")


def lookup(fn):
    start = glyph_js.index("const %s = getLookupTableFactory" % fn)
    end = glyph_js.index("});", start)
    body = glyph_js[start:end]
    pairs = {}
    for m in re.finditer(r't(?:\.([A-Za-z0-9_]+)|\["([^"]+)"\]) = (0x[0-9a-fA-F]+);', body):
        key = m.group(1) or m.group(2)
        pairs.setdefault(key, int(m.group(3), 16))
    return pairs


agl = lookup("getGlyphsUnicode")
dingbats = lookup("getDingbatsGlyphsUnicode")

metrics_js = read("metrics.js")
widths = {}
for m in re.finditer(r't(?:\.([A-Za-z]+)|\["([A-Za-z-]+)"\]) = getLookupTableFactory\(function \(t\) \{(.*?)\}\);', metrics_js, re.S):
    font = m.group(1) or m.group(2)
    table = {}
    for g in re.finditer(r't(?:\.([A-Za-z0-9_]+)|\["([^"]+)"\]) = (\d+);', m.group(3)):
        table[g.group(1) or g.group(2)] = int(g.group(3))
    widths[font] = table

basic = {}
bstart = metrics_js.index("const getFontBasicMetrics")
for m in re.finditer(r't(?:\.([A-Za-z]+)|\["([A-Za-z-]+)"\]) = \{(.*?)\};', metrics_js[bstart:], re.S):
    font = m.group(1) or m.group(2)
    vals = dict((k, int(v)) for k, v in re.findall(r"(\w+): (-?\d+)", m.group(3)))
    basic[font] = vals

lines = []
w = lines.append
w("// @generated by scripts/gen-pdfa-font-tables.py — do not edit by hand.")
w("//")
w("// Data derived from pdf.js (https://github.com/mozilla/pdf.js),")
w("// Copyright Mozilla Foundation, Apache License 2.0: src/core/encodings.js,")
w("// src/core/glyphlist.js (Adobe Glyph List, BSD-3-Clause) and")
w("// src/core/metrics.js (Adobe Core14 AFM widths).")
w("")
w("#![allow(clippy::all, dead_code)]")
w("")
for rust, js in [
    ("STANDARD_ENCODING", "StandardEncoding"),
    ("WIN_ANSI_ENCODING", "WinAnsiEncoding"),
    ("MAC_ROMAN_ENCODING", "MacRomanEncoding"),
    ("MAC_EXPERT_ENCODING", "MacExpertEncoding"),
    ("SYMBOL_ENCODING", "SymbolSetEncoding"),
    ("ZAPF_DINGBATS_ENCODING", "ZapfDingbatsEncoding"),
]:
    names = encoding(js)
    w("pub static %s: [&str; 256] = [" % rust)
    for i in range(0, 256, 8):
        w("    " + " ".join('"%s",' % n for n in names[i:i + 8]))
    w("];")
    w("")

w("/// Adobe Glyph List: glyph name → Unicode, sorted by name.")
w("pub static AGL: &[(&str, u32)] = &[")
for k in sorted(agl):
    w('    ("%s", 0x%04X),' % (k, agl[k]))
w("];")
w("")
w("/// ZapfDingbats glyph names → Unicode, sorted by name.")
w("pub static DINGBATS: &[(&str, u32)] = &[")
for k in sorted(dingbats):
    w('    ("%s", 0x%04X),' % (k, dingbats[k]))
w("];")
w("")
w("/// Standard-14 glyph widths (1/1000 em), sorted by glyph name.")
w("/// The Courier faces are monospaced (600) and not listed.")
for font in sorted(widths):
    ident = "W_" + font.upper().replace("-", "_")
    w("pub static %s: &[(&str, u16)] = &[" % ident)
    for k in sorted(widths[font]):
        w('    ("%s", %d),' % (k, widths[font][k]))
    w("];")
w("")
w("/// (font, ascent, descent, cap height, x height)")
w("pub static STD14_BASIC: &[(&str, i16, i16, i16, i16)] = &[")
for font in sorted(basic):
    b = basic[font]
    w('    ("%s", %d, %d, %d, %d),' % (font, b.get("ascent", 0), b.get("descent", 0), b.get("capHeight", 0), b.get("xHeight", 0)))
w("];")
w("")
w("pub fn std14_widths(font: &str) -> Option<&'static [(&'static str, u16)]> {")
w("    match font {")
for font in sorted(widths):
    w('        "%s" => Some(W_%s),' % (font, font.upper().replace("-", "_")))
w("        _ => None,")
w("    }")
w("}")

os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out_path, len(agl), "agl", len(dingbats), "dingbats", sorted(widths))
